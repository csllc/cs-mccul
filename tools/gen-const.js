'use strict';

// Generate lib/mcculConst.js from the enums in vendor/uldaq/src/uldaq.h.
//
// To expose another UL enum to JS, add its name to ENUMS below and run:
//   node tools/gen-const.js

const fs = require('fs');
const path = require('path');

// Enums to export, in output order, with a short description of each
const ENUMS = {
  DaqDeviceInterface: 'Interface types, used with ulGetDaqDeviceInventory()',
  DevInfoItem:        'Device information items, used with ulDevGetInfo()',
  AiInputMode:        'Analog input modes',
  Range:              'Analog ranges',
  AInFlag:            'Flags for ulAIn()',
  AiInfoItem:         'Analog input information items, used with ulAIGetInfo()',
  DigitalPortType:    'Digital port types',
  DigitalPortIoType:  'Digital port I/O types',
  DigitalDirection:   'Digital port/bit directions, used with ulDConfigPort()',
  DioInfoItem:        'Digital I/O information items, used with ulDIOGetInfo()',
  CtrInfoItem:        'Counter information items, used with ulCtrGetInfo()',
  DaqIInfoItem:       'DAQ input information items, used with ulDaqIGetInfo()',
  DaqInChanType:      'DAQ input channel types, used in ulDaqInScan() channel descriptors',
  ScanOption:         'Scan options (bit flags), used with the *Scan() functions',
  ScanStatus:         'Scan status, returned by the *ScanStatus() functions',
  AInScanFlag:        'Flags for ulAInScan()',
  DInScanFlag:        'Flags for ulDInScan()',
  CInScanFlag:        'Flags for ulCInScan()',
  DaqInScanFlag:      'Flags for ulDaqInScan()',
};

const root = path.resolve(__dirname, '..');
const headerPath = path.join(root, 'vendor/uldaq/src/uldaq.h');
const outputPath = path.join(root, 'lib/mcculConst.js');

// Strip comments
const header = fs.readFileSync(headerPath, 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\/\/.*$/gm, '');

// Simple numeric #defines (e.g. NOSCALEDATA), which some enum values use
const symbols = {};
for (const [, name, expr] of header.matchAll(/^\s*#define\s+(\w+)\s+([-\w\s<|()]+?)\s*$/gm)) {
  try {
    symbols[name] = evaluate(expr, symbols);
  } catch (e) {
    // not a numeric define; ignore
  }
}

// Evaluate a C constant expression (numbers, <<, |, and known symbols)
function evaluate(expr, known) {
  const js = expr.replace(/[A-Za-z_]\w*/g, (id) => {
    if (!(id in known)) throw new Error(`unknown symbol ${id}`);
    return `(${known[id]})`;
  });
  if (!/^[\d\s()<|+\-x]+$/i.test(js)) throw new Error(`unsupported expression ${expr}`);
  return Function(`"use strict"; return (${js});`)();
}

// Parse all typedef'd enums. Enum values can refer to #defines and to values
// from earlier enums, so every parsed value is added to the symbol table.
const enums = {};
for (const [, body, name] of header.matchAll(/typedef\s+enum\s*\{([\s\S]*?)\}\s*(\w+)\s*;/g)) {
  const values = {};
  let next = 0;
  try {
    for (const item of body.split(',').map((s) => s.trim()).filter(Boolean)) {
      const [key, expr] = item.split('=').map((s) => s.trim());
      const value = (expr === undefined) ? next : evaluate(expr, { ...symbols, ...values });
      values[key] = value;
      next = value + 1;
    }
  } catch (err) {
    // Only a problem if this is an enum we export (checked below)
    continue;
  }
  enums[name] = values;
  Object.assign(symbols, values);
}

// Write the module
const lines = [
  "'use strict';",
  '',
  '// Constants from the Measurement Computing Universal Library (uldaq.h).',
  '// Names and values match the C enums so the UL documentation applies directly.',
  '//',
  '// GENERATED by tools/gen-const.js -- edit that script, not this file.',
  '',
];

for (const [name, description] of Object.entries(ENUMS)) {
  if (!enums[name]) {
    console.error(`gen-const: enum ${name} not found in ${headerPath}`);
    process.exit(1);
  }
  const width = Math.max(...Object.keys(enums[name]).map((k) => k.length));
  lines.push(`// ${description}`);
  lines.push(`const ${name} = Object.freeze({`);
  for (const [key, value] of Object.entries(enums[name])) {
    lines.push(`  ${(key + ':').padEnd(width + 1)} ${value},`);
  }
  lines.push('});', '');
}

lines.push(
  '// Return the name of a constant given its enum object and value, e.g.',
  "// nameOf(Range, 5) -> 'BIP10VOLTS'. Where several names share a value",
  '// (e.g. AUXPORT and AUXPORT0), the first one is returned. Returns undefined',
  '// if not found.',
  'function nameOf(enumObject, value) {',
  '  return Object.keys(enumObject).find((key) => enumObject[key] === value);',
  '}',
  '',
  'module.exports = {',
  ...Object.keys(ENUMS).map((name) => `  ${name},`),
  '  nameOf,',
  '};',
  '',
);

fs.writeFileSync(outputPath, lines.join('\n'));
console.log(`Wrote ${path.relative(root, outputPath)} (${Object.keys(ENUMS).length} enums)`);
